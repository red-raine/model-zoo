"""logos/numeric_conflict.py — decide a numeric contradiction EXACTLY, without training anything.

THE GAP THIS CLOSES, MEASURED
----------------------------
`rerank_client` measured the cross-encoder's boundary precisely: it ranks a supporting passage above a
contradicting one in 5/5 triples, but **4 of 5 contradicting passages fall below a 0.5 threshold, so they
are DISCARDED rather than flagged**. Contradiction and off-topic arrive in the same low band.

That is the one thing standing between the pipeline and a reject pile. So the low band must be routed to
something that can *decide*, and for a numeric contradiction that something does not need to be learned:
two passages that both state a length, at 330 and 300, disagree, and no model is required to see it.

WHY NOT TRAIN A CONTRADICTION CLASSIFIER INSTEAD (the 10-minute proposal, priced)
---------------------------------------------------------------------------------
Training is only as good as its labels, and the labels available for free are the ones an oracle
generates:

    numeric contradiction, generated by mutating a value   free and PERFECT  <- but sympy already
                                                                               decides this exactly
    negation flip, generated syntactically                 free, and trained on a distribution we will
                                                           never see at inference
    real prose contradiction                               needs human judgement -- we have ZERO

So the only labels we can manufacture in ten minutes teach the model to reproduce a function we already
have, and scored eight decidable kinds at zero error. The labels that would add capability are the ones we
do not have. Spending ten minutes to re-learn sympy, on a corpus we cannot evaluate except against our own
construction, is the circular-evidence defect this project already names as its biggest weakness.

Hence: this module. Exact, auditable, zero training. A model becomes worth training when there is judged
data to train it on, and that is a labelling project, not a compute one.

WHAT IT CAN AND CANNOT SEE
    catches: 330 m vs 300 m | 1.609344 km vs 1.5 km | 8192 tokens vs 512 tokens
    misses : "programmed cell death" vs "uncontrolled cell proliferation" -- no numbers at all
So it converts part of the low band into REFUTED and leaves the rest as genuinely ambiguous. That is the
honest split, and the size of the remainder is the real measure of how much still needs judgement.

USAGE
    python tools/logos/numeric_conflict.py --self-test
    python tools/logos/numeric_conflict.py --measure
"""

