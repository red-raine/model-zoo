# the five triples rerank_client already labelled support / contradict / off-topic
TRIPLES = [
    ("The Eiffel Tower is 330 metres tall.",
     "The Eiffel Tower stands 330 m high.",
     "The Eiffel Tower is 300 metres tall.",
     "The Eiffel Tower appears in the 1974 film The Towering Inferno."),
    ("One mile is 1.609344 kilometres.",
     "One mile equals exactly 1.609344 kilometres.",
     "One mile is 1.500000 kilometres.",
     "Mile is also a surname in some European families."),
    ("Apoptosis is programmed cell death.",
     "Apoptosis is a form of programmed cell death.",
     "Apoptosis is uncontrolled cell proliferation.",
     "Apoptosis was first described in 1972 by Kerr."),
    ("bge-reranker-v2-m3 accepts inputs up to 8192 tokens.",
     "The served model reports max_input_length of 8192 tokens.",
     "bge-reranker-v2-m3 is limited to 512 tokens.",
     "Qdrant is a vector search engine with HNSW indexing."),
    ("A categorical syllogism has two premises and a conclusion.",
     "A categorical syllogism is a major premise, a minor premise and a conclusion.",
     "A categorical syllogism has three premises and no conclusion.",
     "Aristotle wrote the Prior Analytics, which treats inference."),
]


def measure() -> int:
    print("=== can an exact rule see what the encoder discarded? ===")
    print(f"  {'claim':34s} {'support':>9s} {'contra':>9s} {'off-top':>9s}")
    hit_contra = 0
    false_pos = 0
    for claim, sup, con, off in TRIPLES:
        cs, cc, co = conflicts(claim, sup), conflicts(claim, con), conflicts(claim, off)
        hit_contra += 1 if cc["conflict"] else 0
        false_pos += (1 if cs["conflict"] else 0) + (1 if co["conflict"] else 0)
        print(f"  {claim[:34]:34s} {('CONFLICT' if cs['conflict'] else '-'):>9s}"
              f" {('CONFLICT' if cc['conflict'] else '-'):>9s}"
              f" {('CONFLICT' if co['conflict'] else '-'):>9s}")

    print()
    print(f"  contradicting passages flagged : {hit_contra}/{len(TRIPLES)}")
    print(f"  supporting or off-topic flagged: {false_pos}/{2 * len(TRIPLES)}  (want 0: a false DROP is"
          f" the catastrophic error)")

    print("\n=== what it cannot see, stated rather than hidden ===")
    miss = [(c, con) for c, _s, con, _o in TRIPLES if not conflicts(c, con)["conflict"]]
    for c, con in miss:
        print(f"  MISSED: {c[:50]!r} vs {con[:50]!r}")
    print(f"  {len(miss)} of {len(TRIPLES)} contradictions have no numbers to compare. 'programmed cell")
    print(f"  death' vs 'uncontrolled cell proliferation' needs judgement, and no exact rule will find it.")

    print("\n=== the comparison to the encoder, side by side ===")
    print("  cross-encoder : flagged 4/5 by DISCARDING them (below a support threshold, indistinguishable")
    print("                  from off-topic) -- a low score is not a verdict")
    print(f"  this module   : flags {hit_contra}/{len(TRIPLES)} by NAME, with the two values printed, and")
    print(f"                  raises no false flags on support or off-topic. A verdict that can be audited")
    print(f"                  without rerunning a model.")
    print()
    print("  so the right architecture is the one the measurements forced: the encoder RETRIEVES which")
    print("  passage to examine, and an exact rule DECIDES. Not a trained model substituting for both.")
    return 0


def run_self_test() -> bool:
    print("logos.numeric_conflict - SELF TEST")
    ok = True

    # --- REGRESSION: the greedy-group bug. "330 metres tall" must yield the unit 'metres', not 'tall'.
    got = extract("The tower is 330 metres tall.")
    good = len(got) == 1 and got[0]["family"] == "length" and got[0]["value"] == 330.0
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] '330 metres tall' extracts family=length value=330 "
          f"(the greedy-group bug yielded unit='tall', so nothing was extracted)")

    # --- REGRESSION, found on 200 real AVeriTeC pairs: two YEARS are not a contradiction
    r = conflicts("The number was 1950 in the old report.", "The figure was 2020 in the new report.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 1950 vs 2020 (two dates) does NOT conflict")

    # --- REGRESSION: "75,000 flu deaths last year in 2019" must not read as 75,000 years. The unit word
    #     was 4 positions away and belonged to a different phrase; the window is now adjacent-only.
    r = conflicts("America had 75,000 flu deaths in 2019.", "America had 60,000 flu deaths in 2019.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] a death toll is not read as a duration "
          f"(adjacent-unit window)")

    # --- REGRESSION: a correctly ROUNDED percentage is not a contradiction
    # 28 IS the correct 2-s.f. rounding of 27.63; 27 is not, and flagging it is right. My first version of
    # this test asserted 27 -- the engine was correct and I was not.
    r = conflicts("Imports increased by 28%.", "Imports increased by 27.63%.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 28% vs 27.63% is a correct rounding, not a conflict")

    r = conflicts("Imports increased by 27%.", "Imports increased by 27.63%.")
    good = r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 27% vs 27.63% conflicts (27 is not the 2-s.f. rounding, 28 is)")

    # --- THE CHECK MUST HAVE RUN. An unavailable rounding check used to be swallowed, which made an
    #     unperformed test indistinguishable from a clean result.
    r = conflicts("Imports increased by 28%.", "Imports increased by 27.63%.")
    good = r["rounding_check_errors"] == []
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] the rounding check RAN (no swallowed errors): "
          f"{r['rounding_check_errors'] or 'clean'}")

    # --- and a real disagreement is still caught, so the fix did not defang it
    r = conflicts("Imports increased by 27%.", "Imports increased by 24.7%.")
    good = r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 27% vs 24.7% still conflicts")

    # --- REGRESSION: numbers written as WORDS. "two premises" vs "three premises" is a numeric
    #     contradiction and a digit-only extractor saw nothing at all.
    r = conflicts("A syllogism has two premises.", "A syllogism has three premises.")
    good = r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 'two premises' vs 'three premises' conflicts "
          f"(word-form numbers)")

    # --- and word forms compare against digits, so "three layers" vs "3 layers" agrees
    r = conflicts("The model has three layers.", "The model has 3 layers.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 'three layers' vs '3 layers' agree across numeral forms")

    # --- a same-family disagreement is caught
    r = conflicts("The tower is 330 metres tall.", "The tower is 300 metres tall.")
    good = r["conflict"] and r["disagreements"][0]["family"] == "length"
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 330 m vs 300 m conflicts (family=length)")

    # --- agreement is not a conflict
    r = conflicts("The tower is 330 metres tall.", "The tower stands 330 m high.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 330 m vs 330 m does NOT conflict")

    # --- DIFFERENT FAMILIES NEVER CONFLICT. This is the false-positive guard: "1974" is a year, not a
    #     length, and treating every shared number as comparable would flag a film reference.
    r = conflicts("The Eiffel Tower is 330 metres tall.",
                  "The Eiffel Tower appears in the 1974 film The Towering Inferno.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 330 metres vs 1974 (no unit family) does NOT conflict")

    # --- unit normalisation: 1.5 km and 1500 m agree, so only a REAL disagreement is flagged
    r = conflicts("The route is 1.5 km long.", "The route is 1500 metres long.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 1.5 km vs 1500 m normalise to agreement, not a conflict")

    # --- miles normalise too, so 1 mile vs 1609.344 m agrees
    r = conflicts("One mile is 1.609344 kilometres.", "One mile is 1609.344 metres.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 1.609344 km vs 1609.344 m agree after normalisation")

    # --- and a real mile disagreement is still caught
    r = conflicts("One mile is 1.609344 kilometres.", "One mile is 1.5 kilometres.")
    good = r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 1.609344 km vs 1.5 km conflicts")

    # --- no numbers at all is NOT a conflict, it is out of scope. Fail closed on the flag, not on truth.
    r = conflicts("Apoptosis is programmed cell death.",
                  "Apoptosis is uncontrolled cell proliferation.")
    good = not r["conflict"] and r["n_claim_nums"] == 0
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] a non-numeric contradiction is OUT OF SCOPE, not a conflict")

    # --- a bare number never conflicts: it has no family, so it cannot be compared
    r = conflicts("It was released in 1974.", "It came out in 1999.")
    good = not r["conflict"]
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] 1974 vs 1999 with no unit is not compared (no free flags)")

    # --- the result accounts for what it did not look at
    r = conflicts("The tower is 330 metres tall and has 3 million visitors.",
                  "The tower is 300 metres tall.")
    good = "uncompared_claim" in r and isinstance(r["uncompared_claim"], list)
    ok = ok and good
    print(f"  [{'PASS' if good else 'FAIL'}] the result lists the numbers it could NOT compare")

    print(f"SELF TEST: {'ALL PASS' if ok else 'FAILURES'}")
    return ok


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Exact numeric contradiction detection.")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--measure", action="store_true")
    ap.add_argument("--claim", default="")
    ap.add_argument("--passage", default="")
    args = ap.parse_args(argv)
    if args.self_test:
        return 0 if run_self_test() else 1
    if args.measure:
        return measure()
    if args.claim and args.passage:
        import json
        print(json.dumps(conflicts(args.claim, args.passage), indent=2))
        return 0
    return 0 if run_self_test() else 1


if __name__ == "__main__":
    raise SystemExit(main())
